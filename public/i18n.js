let lang = 'th';

export function setLang(next) {
  lang = STRINGS[next] ? next : 'th';
  document.documentElement.lang = lang;
}

export function getLang() {
  return lang;
}

export function t(key, vars = {}) {
  const text = STRINGS[lang][key] ?? STRINGS.th[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : ''));
}

export function formatDuration(totalMinutes) {
  const min = Math.max(0, Math.round(totalMinutes));
  const h = Math.floor(min / 60);
  const m = min % 60;
  if (!h) return t('dur.min', { m });
  return m ? t('dur.hrMin', { h, m }) : t('dur.hr', { h });
}

export function locale() {
  return lang === 'th' ? 'th-TH' : 'en-GB';
}
